# 1. In operator 

# this operator is to check the value inside .


Fruits=['Mango','Orange','Banana']

print("Mango" in Fruits)

print("Grapes" in Fruits)


vegetable=['carrot','potato','tomato']

print("carrot" in vegetable)

print("Onion" in vegetable)



car=['RR','BMW','TATA']

print("RR" in car)

print("Toyota" in car)



